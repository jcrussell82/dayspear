// Builds the static site into /public from the source parts in client/src.
//   node build.mjs            → public/index.html, app.css, app.js, config.js, assets/*
//   node build.mjs --single   → also writes public/dayspear-demo.html, one self-contained demo file
// No dependencies. GitHub Pages serves /public as-is.
//
// config.js tells the site where your Supabase project is. It's built from two environment
// variables (in GitHub: Settings › Secrets and variables › Actions › Variables):
//   SUPABASE_URL       https://<project-ref>.supabase.co
//   SUPABASE_ANON_KEY  the project's anon / publishable key — designed to be public
// Without them the site runs as the demo (sample data only).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, 'client', 'src');
const ASSETS = path.join(ROOT, 'client', 'assets');
const OUT = path.join(ROOT, 'public');

// Order matters: markup first, then the script parts; the router (p5g) runs last.
const ORDER = ['p1_head', 'p2_appcss', 'p3_home', 'p4_app',
  'p5a_js', 'p5b_js', 'p5c_js', 'p5d_js', 'p5e_js', 'p5f_js', 'p5h_js', 'p5i_js', 'p5j_js',
  'p5k_js', 'p5l_js', 'p5m_js', 'p5n_js', 'p5o_js', 'p5q_real', 'p5g_js'];

const ASSET_MAP = {
  LOGO: 'logo.svg', LOGOMARK: 'logomark.svg', LOGO_WHITE: 'logo-white.svg', PATTERN: 'pattern.jpg', HERO: 'hero.jpg', TEAM: 'team.jpg',
  ...Object.fromEntries([1, 2, 3, 4, 5, 6, 7, 8, 9].map(n => [`AV_e${n}`, `demo-av-e${n}.jpg`])),
};

let html = ORDER.map(n => fs.readFileSync(path.join(SRC, n + '.html'), 'utf8')).join('\n');

const styleStart = html.indexOf('<style>'), styleEnd = html.indexOf('</style>');
const scriptStart = html.indexOf('<script>'), scriptEnd = html.lastIndexOf('</script>');
if (styleStart < 0 || styleEnd < 0 || scriptStart < 0 || scriptEnd < 0) throw new Error('Could not find <style> or <script> in the source parts.');
const css = html.slice(styleStart + 7, styleEnd);
const js = html.slice(scriptStart + 8, scriptEnd);
const SB_URL = (process.env.SUPABASE_URL || '').trim().replace(/\/$/, '');
const SB_KEY = (process.env.SUPABASE_ANON_KEY || process.env.SUPABASE_PUBLISHABLE_KEY || '').trim();
// Refuse to publish a secret key by mistake: only the public (anon / publishable) key belongs in the site.
if (SB_KEY.startsWith('sb_secret_') || (SB_KEY.startsWith('eyJ') && /service_role/.test(Buffer.from(SB_KEY.split('.')[1] || '', 'base64').toString()))) {
  console.error('SUPABASE_ANON_KEY looks like the SECRET service key. Use the anon / publishable key instead.'); process.exit(1);
}
if (SB_URL && !/^https?:\/\/[\w.:-]+$/.test(SB_URL)) { console.error('SUPABASE_URL should look like https://<project-ref>.supabase.co'); process.exit(1); }
// No inline scripts or third-party code: only this site and your Supabase project.
// Google Tag Manager / Analytics are allowed here but only loaded on public marketing pages (see p5q_real).
const GA = 'https://*.google-analytics.com https://*.analytics.google.com https://*.googletagmanager.com';
const csp = ["default-src 'self'", "script-src 'self' https://www.googletagmanager.com", "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com", "font-src 'self' https://fonts.gstatic.com",
  `img-src 'self' data: blob: ${GA}`, `connect-src 'self'${SB_URL ? ' ' + SB_URL : ''} ${GA}`, "base-uri 'self'", "form-action 'self'"].join('; ');
const page = html.slice(0, styleStart).replace('<meta charset="utf-8">', `<meta charset="utf-8">\n<meta http-equiv="Content-Security-Policy" content="${csp}">`)
  + '<link rel="stylesheet" href="app.css">' + html.slice(styleEnd + 8, scriptStart) + '<script src="config.js"></script>\n<script src="app.js" defer></script>' + html.slice(scriptEnd + 9);

const left = s => (s.match(/\{\{[A-Za-z_0-9]+\}\}/g) || []);
const withPaths = s => s.replace(/\{\{([A-Za-z_0-9]+)\}\}/g, (m, k) => (ASSET_MAP[k] ? `assets/${ASSET_MAP[k]}` : m));

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'assets'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'index.html'), withPaths(page));
fs.writeFileSync(path.join(OUT, 'app.css'), withPaths(css));
fs.writeFileSync(path.join(OUT, 'app.js'), withPaths(js));
fs.writeFileSync(path.join(OUT, 'config.js'), `// Generated by build.mjs — public settings only.\nwindow.DAYSPEAR_CONFIG = ${JSON.stringify(SB_URL && SB_KEY ? { supabaseUrl: SB_URL, supabaseAnonKey: SB_KEY } : {})};\n`);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
for (const f of fs.readdirSync(ASSETS)) fs.copyFileSync(path.join(ASSETS, f), path.join(OUT, 'assets', f));
fs.writeFileSync(path.join(OUT, '404.html'), withPaths(page)); // GitHub Pages fallback

const missing = [...new Set([...left(withPaths(page)), ...left(withPaths(css)), ...left(withPaths(js))])];
if (missing.length) { console.error('Unreplaced placeholders:', missing.join(', ')); process.exit(1); }

if (process.argv.includes('--single')) {
  const mime = f => (f.endsWith('.svg') ? 'image/svg+xml' : 'image/jpeg');
  const inline = s => s.replace(/\{\{([A-Za-z_0-9]+)\}\}/g, (m, k) => `data:${mime(ASSET_MAP[k])};base64,${fs.readFileSync(path.join(ASSETS, ASSET_MAP[k])).toString('base64')}`);
  fs.writeFileSync(path.join(OUT, 'dayspear-demo.html'), inline(html));
}
const kb = f => Math.round(fs.statSync(path.join(OUT, f)).size / 1024) + ' KB';
console.log(`Built public/: index.html ${kb('index.html')}, app.css ${kb('app.css')}, app.js ${kb('app.js')} · ${SB_URL && SB_KEY ? 'connected to ' + SB_URL : 'demo only (no SUPABASE_URL / SUPABASE_ANON_KEY)'}`);
